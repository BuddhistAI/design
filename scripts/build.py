#!/usr/bin/env python3
"""Build the BuddhistAI design system from tokens.json.

Writes:
  css/tokens.css        CSS custom properties, light and dark
  buddhistai.css        tokens + base + components in one file (what sites link or copy)
  tailwind.preset.js    Tailwind preset that points at the CSS variables
  tokens.js             The same tokens as a JS module (React, charts)

Run:  python3 scripts/build.py          (write files)
      python3 scripts/build.py --check  (fail if any file is out of date)
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = json.loads((ROOT / 'tokens.json').read_text())
V = T['version']


def colors(mode):
    return {k: v['value'] for k, v in T['color'][mode].items()}


def decl(d, indent='  '):
    return '\n'.join(f'{indent}--{k}: {v};' for k, v in d.items())


def tokens_css():
    static = {}
    for k, v in T['font'].items():
        if k != 'google':
            static[f'f-{k}'] = v['value']
    for k, v in T['size'].items():
        static[k] = v['value']
    for k, v in T['space'].items():
        static[f's-{k}'] = v
    for k, v in T['radius'].items():
        static[f'r-{k}'] = v['value']
    static['r'] = T['radius']['md']['value']  # homepage shorthand
    for k, v in T['shadow'].items():
        static[f'shadow-{k}'] = v['value']
    for k, v in T['layout'].items():
        static[k] = v['value']
    for k, v in T['color']['medal'].items():
        static[f'medal-{k}'] = v['value']
        static[f'medal-{k}-on'] = v['on']
    dark = decl(colors('dark'), '  ')
    return f'''/* BuddhistAI design tokens {V}. Generated from tokens.json by scripts/build.py. Do not edit. */
/* Fonts: <link rel="stylesheet" href="{T['font']['google']['value']}"> */
:root {{
{decl(colors('light'))}
{decl(static)}
  color-scheme: light;
}}
@media (prefers-color-scheme: dark) {{
  :root:not([data-theme="light"]) {{
{decl(colors('dark'), '    ')}
    color-scheme: dark;
  }}
}}
:root[data-theme="dark"] {{
{dark}
  color-scheme: dark;
}}
'''


def bundle(tok):
    parts = [tok]
    for f in ('base.css', 'components.css'):
        parts.append((ROOT / 'css' / f).read_text())
    head = f'/* BuddhistAI design system {V}. https://github.com/BuddhistAI/design. Generated by scripts/build.py; edit tokens.json and css/*.css instead. */\n'
    return head + '\n'.join(parts)


def tailwind():
    names = list(T['color']['light'])
    cols = ',\n'.join(f"        '{n}': 'var(--{n})'" for n in names)
    return f'''// BuddhistAI Tailwind preset {V}. Generated by scripts/build.py. Load buddhistai.css (or css/tokens.css) too: colors are CSS variables, so dark mode just works.
module.exports = {{
  theme: {{
    extend: {{
      colors: {{
{cols}
      }},
      fontFamily: {{
        display: ['var(--f-display)'],
        sans: ['var(--f-body)'],
        mono: ['var(--f-mono)'],
        bo: ['var(--f-bo)'],
      }},
      borderRadius: {{ xs: 'var(--r-xs)', sm: 'var(--r-sm)', md: 'var(--r-md)', lg: 'var(--r-lg)', xl: 'var(--r-xl)' }},
      maxWidth: {{ page: 'var(--max-width)', reading: 'var(--reading)' }},
    }},
  }},
}};
'''


def js():
    out = {'version': V, 'light': colors('light'), 'dark': colors('dark'),
           'medal': {k: v for k, v in T['color']['medal'].items()},
           'font': {k: v['value'] for k, v in T['font'].items()},
           'radius': {k: v['value'] for k, v in T['radius'].items()},
           'space': T['space']}
    return f'// BuddhistAI design tokens {V}. Generated by scripts/build.py.\nexport const tokens = {json.dumps(out, indent=2, ensure_ascii=False)};\nexport default tokens;\n'


def main():
    tok = tokens_css()
    files = {'css/tokens.css': tok, 'buddhistai.css': bundle(tok), 'tailwind.preset.js': tailwind(), 'tokens.js': js()}
    stale = []
    for name, text in files.items():
        p = ROOT / name
        if '--check' in sys.argv:
            if not p.exists() or p.read_text() != text:
                stale.append(name)
        else:
            p.write_text(text)
    if stale:
        sys.exit('Out of date, run python3 scripts/build.py: ' + ', '.join(stale))
    print('ok' if '--check' in sys.argv else 'built ' + ', '.join(files))


if __name__ == '__main__':
    main()
